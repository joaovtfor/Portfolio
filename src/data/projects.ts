import { z } from "zod";

export const ProjectSchema = z.object({
  slug: z.string().regex(/^[a-z0-9-]+$/),
  title: z.string(),
  subtitle: z.string(),
  /** Empresa onde o projeto foi desenvolvido (contexto para quem lê). */
  company: z.string(),
  /** Texto de entrada: o que é o projeto e o que foi entregue, em até duas frases curtas. */
  description: z.string(),
  image: z.string().startsWith("/projects/"),
  /** Apenas tecnologias (viram badges), da mais relevante para a menos: o card mostra as 3 primeiras. */
  stack: z.array(z.string()),
  highlights: z.array(z.string()),
  link: z.string().url().optional(),
  isPrivate: z.boolean(),
});

export type Project = z.infer<typeof ProjectSchema>;

